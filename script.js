const body = document.body;
const langToggle = document.getElementById("langToggle");
const themeToggle = document.getElementById("themeToggle");
const themeIcon = themeToggle.querySelector(".theme-icon");
const revealItems = document.querySelectorAll(".reveal");
const downloadCvBtn = document.getElementById("downloadCvBtn");

const savedLang = localStorage.getItem("portfolio-language") || "ar";
const savedTheme = localStorage.getItem("portfolio-theme") || "dark";

function setLanguage(lang) {
  const dict = translations[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  body.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });

  langToggle.textContent = lang === "ar" ? "EN" : "AR";
  localStorage.setItem("portfolio-language", lang);
}

function setTheme(theme) {
  body.classList.toggle("light-theme", theme === "light");
  themeIcon.textContent = theme === "light" ? "☾" : "☀";
  localStorage.setItem("portfolio-theme", theme);
}

langToggle.addEventListener("click", () => {
  const nextLang = document.documentElement.lang === "ar" ? "en" : "ar";
  setLanguage(nextLang);
});

themeToggle.addEventListener("click", () => {
  const nextTheme = body.classList.contains("light-theme") ? "dark" : "light";
  setTheme(nextTheme);
});

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
      }
    });
  },
  { threshold: 0.16 }
);

revealItems.forEach((item, index) => {
  item.style.transitionDelay = `${index * 90}ms`;
  observer.observe(item);
});

downloadCvBtn?.addEventListener("click", async (event) => {
  event.preventDefault();

  const fileUrl = downloadCvBtn.getAttribute("href");
  const fileName = downloadCvBtn.getAttribute("download") || "Essam-Hamood-Abdo-CV.pdf";

  try {
    const response = await fetch(fileUrl);
    if (!response.ok) throw new Error("CV file not found");

    const blob = await response.blob();
    const blobUrl = URL.createObjectURL(blob);
    const tempLink = document.createElement("a");
    tempLink.href = blobUrl;
    tempLink.download = fileName;
    document.body.appendChild(tempLink);
    tempLink.click();
    tempLink.remove();
    URL.revokeObjectURL(blobUrl);
  } catch (error) {
    alert(document.documentElement.lang === "ar"
      ? "ملف السيرة الذاتية غير موجود حاليًا. أرسل ملف PDF لأربطه لك."
      : "The CV PDF is not available yet. Send the PDF file and I will attach it.");
  }
});

setLanguage(savedLang);
setTheme(savedTheme);
